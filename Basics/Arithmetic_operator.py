a=10
b=20

# Arithmetic operations
print("a + b =", a + b)  # Output: a + b = 30
print(type(a + b))        # Output: <class 'int'>
print("a - b =", a - b)  # Output: a - b = -10
print(type(a - b))        # Output: <class 'int'>
print("a * b =", a * b)  # Output: a * b = 200
print(type(a * b))        # Output: <class 'int'>
print("b / a =", b / a)  # Output: b / a = 2.0
print(type(b / a))        # Output: <class 'float'>

# Modulus operator
print("b % a =", b % a)  # Output: b % a = 0
print(type(b % a))        # Output: <class 'int'>
a=2
print("b ** a =", b ** a) # Output: b ** a = 10000000000
print(type(b ** a))       # Output: <class 'int'>