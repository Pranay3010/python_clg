# > , <, ==, !=, >=, <=
a=10
b=20

print("a > b:", a > b)   # Output: a > b: False
print("a < b:", a < b)   # Output: a < b: True
print("a == b:", a == b) # Output: a == b: False
print("a != b:", a != b) # Output: a != b: True
print("a >= b:", a >= b) # Output: a >= b: False
print("a <= b:", a <= b) # Output: a <= b: True

print(type(a > b))   # Output: <class 'bool'>
print(type(a < b))   # Output: <class 'bool'>
print(type(a == b)) # Output: <class 'bool'>
print(type(a != b)) # Output: <class 'bool'>
print(type(a >= b)) # Output: <class 'bool'>
print(type(a <= b)) # Output: <class 'bool'>